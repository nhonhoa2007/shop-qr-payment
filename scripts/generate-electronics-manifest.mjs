// Helper to construct laptop specs
function makeLaptopSpecs(cpu, ram, ssd, display, res, refresh, weight, os) {
  return {
    schemaVersion: 1,
    values: {
      cpu: { state: 'KNOWN', value: cpu },
      ram: { state: 'KNOWN', value: ram, unit: 'GB' },
      ssd: { state: 'KNOWN', value: ssd, unit: 'GB' },
      display_size: { state: 'KNOWN', value: display, unit: 'inch' },
      resolution: { state: 'KNOWN', value: res },
      refresh_rate: { state: 'KNOWN', value: refresh, unit: 'Hz' },
      weight: { state: 'KNOWN', value: weight, unit: 'kg' },
      os: { state: 'KNOWN', value: os },
      nfc: { state: 'UNSUPPORTED' },
    },
  };
}

// Helper to construct phone specs
function makePhoneSpecs(chipset, ram, storage, screen, battery, camera, is5g, os, nfc = true) {
  return {
    schemaVersion: 1,
    values: {
      chipset: { state: 'KNOWN', value: chipset },
      ram: { state: 'KNOWN', value: ram, unit: 'GB' },
      storage: { state: 'KNOWN', value: storage, unit: 'GB' },
      screen_size: { state: 'KNOWN', value: screen, unit: 'inch' },
      battery_capacity: { state: 'KNOWN', value: battery, unit: 'mAh' },
      camera_main: { state: 'KNOWN', value: camera, unit: 'MP' },
      is_5g: { state: 'KNOWN', value: is5g },
      os: { state: 'KNOWN', value: os },
      nfc: { state: 'KNOWN', value: nfc },
    },
  };
}

// Helper to construct accessory specs
function makeAccessorySpecs(conn, power, ports, fast, battery, weight) {
  return {
    schemaVersion: 1,
    values: {
      connection_type: { state: 'KNOWN', value: conn },
      power_output: power ? { state: 'KNOWN', value: power, unit: 'W' } : { state: 'UNSUPPORTED' },
      ports: ports ? { state: 'KNOWN', value: ports } : { state: 'UNSUPPORTED' },
      fast_charging: fast !== undefined ? { state: 'KNOWN', value: fast } : { state: 'UNSUPPORTED' },
      battery_capacity: battery ? { state: 'KNOWN', value: battery, unit: 'mAh' } : { state: 'UNSUPPORTED' },
      weight: { state: 'KNOWN', value: weight, unit: 'g' },
    },
  };
}

